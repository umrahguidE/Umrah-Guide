/**
 * Downloads real recitations — human voices, not the phone's speech engine —
 * for the Arabic the app shows, and writes audio/duas/index.json, the list the
 * app plays from.
 *
 *   node scripts/fetch-recitations.mjs            # al-Ḥuṣarī is the default Qur'an reciter
 *   node scripts/fetch-recitations.mjs alafasy    # pick a different default
 *
 * The 3 Qur'anic verses are small (one āyah each), so ALL 5 reciters are
 * fetched for each — the default plays at audio/duas/{id}.mp3, every reciter
 * (default included) also gets audio/duas/{id}-{reciterKey}.mp3, and the
 * index lists them all under "alternates" so the pilgrim can pick a reciter
 * they find easier to follow, in Settings.
 *
 * The 8 Sunnah duas are a single fixed Ḥiṣn al-Muslim recording each (the
 * site does not name the reciter, and does not offer alternatives) — no
 * reciter choice for those. Some of these recordings read the whole hadith,
 * not only the words of the dua; the index says which.
 *
 * LICENCE: recordings belong to their reciters and publishers. They are
 * fetched at build time rather than committed. Check the terms before
 * publishing the app, or commission your own recordings.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { RECITERS, QURAN, HISN } from './recitation-sources.mjs';

const key = (process.argv[2] ?? 'husary').toLowerCase();
const reciter = RECITERS[key];
if (!reciter) {
  console.error(`Unknown reciter "${key}". Choose one of: ${Object.keys(RECITERS).join(', ')}`);
  process.exit(1);
}

const root = fileURLToPath(new URL('..', import.meta.url));
await mkdir(`${root}audio/duas`, { recursive: true });

const pad = (n, w) => String(n).padStart(w, '0');
const files = {};

async function fetchBytes(url, label, target) {
  process.stdout.write(`${target.padEnd(34)} ← ${label} … `);
  const res = await fetch(url).catch((err) => ({ ok: false, status: err.message }));
  if (!res.ok) {
    console.log(`failed (${res.status})`);
    return null;
  }
  const bytes = Buffer.from(await res.arrayBuffer());
  console.log(`${Math.round(bytes.length / 1024)} KB`);
  return bytes;
}

for (const [id, v] of Object.entries(QURAN)) {
  const alternates = {};
  for (const [reciterKey, r] of Object.entries(RECITERS)) {
    const url = `https://everyayah.com/data/${r.path}/${pad(v.surah, 3)}${pad(v.ayah, 3)}.mp3`;
    const target = `audio/duas/${id}-${reciterKey}.mp3`;
    const bytes = await fetchBytes(url, `${v.label} — ${r.name}`, target);
    if (!bytes) continue;
    await writeFile(`${root}${target}`, bytes);
    const meta = { reciter: r.name, file: `./${target}`, bytes: bytes.length, source: url };
    alternates[reciterKey] = meta;
    if (reciterKey === key) {
      // The default reciter's file also plays from the plain, un-suffixed
      // path so anything reading files[id].file directly keeps working —
      // same bytes, written once, no second download.
      const plain = `audio/duas/${id}.mp3`;
      await writeFile(`${root}${plain}`, bytes);
      files[id] = { kind: 'quran', reciter: r.name, label: v.label, file: `./${plain}`, bytes: bytes.length, source: url, alternates };
    }
  }
}

for (const [id, h] of Object.entries(HISN)) {
  const url = `https://www.hisnmuslim.com/audio/ar/${h.item}.mp3`;
  const target = h.file ?? `audio/duas/${id}.mp3`;
  const bytes = await fetchBytes(url, `Ḥiṣn al-Muslim no. ${h.item}`, target);
  if (!bytes) continue;
  await writeFile(`${root}${target}`, bytes);
  files[id] = { kind: 'hisn', reciter: 'Ḥiṣn al-Muslim recording', label: `Ḥiṣn al-Muslim no. ${h.item}`, file: `./${target}`, bytes: bytes.length, source: url, narration: h.narration };
}

await writeFile(
  `${root}audio/duas/index.json`,
  `${JSON.stringify(
    {
      note: 'Recitations the app plays for the Arabic. Generated by scripts/fetch-recitations.mjs.',
      quranReciter: reciter.name,
      reciters: Object.fromEntries(Object.entries(RECITERS).map(([k, r]) => [k, r.name])),
      sources: ['everyayah.com (Qur’an)', 'hisnmuslim.com (Ḥiṣn al-Muslim)'],
      licence: 'Recordings belong to their reciters and publishers — check the terms before distributing.',
      files,
    },
    null,
    2,
  )}\n`,
);

console.log(`\nDone: ${Object.keys(files).length} recitations, ${Object.values(files).reduce((n, f) => n + Object.keys(f.alternates ?? {}).length, 0)} reciter alternates. Default Qur'an reciter: ${reciter.name}.`);
